//  of progress — cleared vs. remaining, high-traffic first — regenerated each
//  session into `docs/citations/progress.md` so we resume cleanly day to day.
//
//  Reads the SAME live state the app grades on (`CitationBacklog` + the engine),
//  so it can't claim a cell is cleared unless the engine agrees.
//

import Foundation

enum CitationLedger {

    struct Tally: Hashable {
        let total: Int
        let cited: Int
        let needsSecondSource: Int
        let pending: Int
        let blocked: Int
        var remaining: Int { total - cited - blocked }
        var percent: Int { total == 0 ? 0 : Int((Double(cited) / Double(total)) * 100) }
    }

    /// Tally over the actionable worklist (cells + certifier claims).
    static func tally(_ items: [CitationBacklog.Item]) -> Tally {
        Tally(
            total: items.count,
            cited: items.filter { $0.status == "cited" }.count,
            needsSecondSource: items.filter { $0.status == "needsSecondSource" }.count,
            pending: items.filter { $0.status == "pending" && !$0.blocked }.count,
            blocked: items.filter { $0.blocked }.count
        )
    }

    static func markdown(on date: Date = Date()) -> String {
        let items = CitationBacklog.items
        let all = tally(items)
        let highTraffic = tally(items.filter { $0.isHighTraffic })
        let df = DateFormatter(); df.dateFormat = "yyyy-MM-dd"
        let onFile = CitationStore.shared.totalCitationCount

        var md = """
        # Citation Progress — \(df.string(from: date))

        Generated by `CitationLedger` from the live engine. **\(all.cited)/\(all.total)
        cleared (\(all.percent)%)** · \(all.needsSecondSource) need a 2nd source ·
        \(all.pending) pending · \(all.blocked) blocked · \(onFile) citations on file.

        High-traffic (the leverage): **\(highTraffic.cited)/\(highTraffic.total) cleared**,
        \(highTraffic.remaining) remaining — research these first.

        ## Remaining high-traffic worklist

        | ★ | Subject | Origin | Position | Draft | Sources | Status |
        |---|---|---|---|---|---|---|

        """
        let remainingHT = items.filter { $0.isHighTraffic && $0.status != "cited" && !$0.blocked }
        for it in remainingHT {
            let draft = it.draftGrade.map { "\($0) \(it.draftGradeName ?? "")" } ?? "satisfies"
            md += "| ★ | \(it.subject) | \(it.origin ?? "—") | \(it.position) | \(draft) | \(it.sourcesNeeded) | \(it.status) |\n"
        }
        if remainingHT.isEmpty { md += "| | _all high-traffic cells cleared_ | | | | | |\n" }

        md += """

        ## Cleared so far

        """
        let cleared = items.filter { $0.status == "cited" }
        if cleared.isEmpty {
            md += "_None yet — `Citations.json` ships empty by design. Cells stay pending at their conservative grade until a real, approved source clears them._\n"
        } else {
            for it in cleared {
                md += "- `\(it.key)`\n"
            }
        }

        md += "\n_Next: research a batch (high-traffic first) → stage in `docs/citations/candidates/` → owner approves → `CitationCommitter` → regenerate this ledger._\n"
        return md
    }
}
