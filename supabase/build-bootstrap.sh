#!/usr/bin/env bash
# Regenerates supabase/bootstrap.sql by concatenating, in order, every SQL file
# needed to stand up a Haliable backend from an empty Supabase project.
#
# bootstrap.sql is GENERATED — never hand-edit it. Edit the migration it came from
# and re-run this script, or the two will drift. It exists so a disaster recovery
# is one paste into the dashboard SQL Editor rather than seven in the right order.
#
#   ./supabase/build-bootstrap.sh
set -euo pipefail
cd "$(dirname "$0")/.."

OUT=supabase/bootstrap.sql
FILES=(
  supabase-setup.sql
  supabase/migrations/0001_stores_atlas.up.sql
  # 0002 is deliberately skipped: it seeds five INVENTED demo stores that 0007
  # immediately deletes. A fresh bootstrap should never create them at all.
  supabase/migrations/0003_stores_submit.up.sql
  supabase/migrations/0004_rls_hardening.up.sql
  supabase/migrations/0005_store_votes.up.sql
  supabase/migrations/0006_account_lifecycle.up.sql
)
# 0007 only exists once the real store list is approved.
[ -f supabase/migrations/0007_real_stores.up.sql ] && \
  FILES+=(supabase/migrations/0007_real_stores.up.sql)
[ -f supabase/migrations/0008_security_hardening.up.sql ] && \
  FILES+=(supabase/migrations/0008_security_hardening.up.sql)
[ -f supabase/migrations/0009_review_evidence.up.sql ] && \
  FILES+=(supabase/migrations/0009_review_evidence.up.sql)
[ -f supabase/migrations/0010_campus_cafes.up.sql ] && \
  FILES+=(supabase/migrations/0010_campus_cafes.up.sql)
[ -f supabase/migrations/0011_storrs_places.up.sql ] && \
  FILES+=(supabase/migrations/0011_storrs_places.up.sql)

{
  echo "-- ============================================================================"
  echo "-- bootstrap.sql — GENERATED by supabase/build-bootstrap.sh on $(date +%Y-%m-%d)."
  echo "-- DO NOT EDIT. Edit the source migration and re-run the script."
  echo "--"
  echo "-- Stands up a Haliable backend from an empty Supabase project: paste the whole"
  echo "-- file into the dashboard SQL Editor and run it once. Every statement is"
  echo "-- idempotent, so re-running is safe."
  echo "--"
  echo "-- Requires the postgis extension, which 0001 enables."
  echo "-- ============================================================================"
  for f in "${FILES[@]}"; do
    echo
    echo "-- ─────────────────────────────────────────────────────────────────────────"
    echo "-- source: $f"
    echo "-- ─────────────────────────────────────────────────────────────────────────"
    echo
    cat "$f"
  done
} > "$OUT"

echo "wrote $OUT ($(wc -l < "$OUT" | tr -d ' ') lines from ${#FILES[@]} files)"
